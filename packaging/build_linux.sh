#!/usr/bin/env bash
# Empaquetado Linux (Fase 8, F8-4, RF-30): binario onefile + AppImage + .deb/.rpm.
#
# Requiere, ya instalados en el PATH (F8-5 los instala en el runner de CI; en local hay
# que instalarlos a mano, este script no instala nada por sí mismo):
#   - `pyinstaller` (pip install -e ".[packaging]" o del venv de desarrollo)
#   - `linuxdeploy` + `appimagetool` (AppImage) — https://github.com/linuxdeploy/linuxdeploy
#     y https://github.com/AppImage/appimagetool
#   - `fpm` (.deb/.rpm) — `gem install --no-document fpm` (necesita Ruby)
#   - `rpmbuild` en el PATH si se construye el `.rpm` (paquete `rpm` de la distro)
#
# Empaquetado snap: fuera de alcance de v1 (solo se documenta como evolución futura;
# no hay `snapcraft.yaml` en este repo todavía).
set -euo pipefail

RAIZ="$(cd "$(dirname "${BASH_SOURCE[0]}")/.." && pwd)"
DIST="$RAIZ/dist"
VERSION="$(python3 -c "import tomllib; print(tomllib.load(open('$RAIZ/pyproject.toml','rb'))['project']['version'])")"

echo "== Vigía-eew $VERSION — empaquetado Linux =="

# Icon theme lookup, not a path: `Icon=vigia-eew` in the desktop entry resolves
# against hicolor, so every file has to land with that exact basename. A size
# the theme lacks is not an error anywhere -- it is a blurry panel icon.
TAMANOS_ICONO=(16 22 24 32 48 64 128 256 512)

instalar_iconos_hicolor() {
    local destino="$1"
    local lado
    for lado in "${TAMANOS_ICONO[@]}"; do
        install -Dm 0644 "$RAIZ/packaging/icons/vigia-eew-$lado.png" \
            "$destino/usr/share/icons/hicolor/${lado}x${lado}/apps/vigia-eew.png"
    done
    install -Dm 0644 "$RAIZ/packaging/icons/vigia-eew.svg" \
        "$destino/usr/share/icons/hicolor/scalable/apps/vigia-eew.svg"
}

# Same gate CI runs before any packaging job (REQ-OPS-007). A local build --
# which is how the v1.0.0 .deb was made -- skipped it entirely and shipped a
# package with no desktop entry.
python3 "$RAIZ/scripts/check_packaging_assets.py" "$RAIZ"

echo "-- 1/3: binario onefile (PyInstaller) --"
pyinstaller --noconfirm --clean --distpath "$DIST" --workpath "$RAIZ/build" \
    "$RAIZ/packaging/vigia-eew.spec"
BIN="$DIST/vigia-eew"
test -x "$BIN"

echo "-- 2/3: AppImage --"
if command -v linuxdeploy >/dev/null && command -v appimagetool >/dev/null; then
    APPDIR="$RAIZ/build/AppDir"
    rm -rf "$APPDIR"
    mkdir -p "$APPDIR/usr/bin"
    cp "$BIN" "$APPDIR/usr/bin/vigia-eew"
    # Desktop entry and icons are repository files now, generated by
    # `packaging/make_icons.py`: the AppImage, the .deb and the .rpm install
    # the same mark, and no build script draws one of its own.
    install -Dm 0644 "$RAIZ/packaging/vigia-eew.desktop" "$APPDIR/vigia-eew.desktop"
    install -Dm 0644 "$RAIZ/packaging/icons/vigia-eew-256.png" "$APPDIR/vigia-eew.png"
    instalar_iconos_hicolor "$APPDIR"

    linuxdeploy --appdir "$APPDIR" --desktop-file "$APPDIR/vigia-eew.desktop" \
        --icon-file "$APPDIR/vigia-eew.png" --output appimage
    mv ./*.AppImage "$DIST/vigia-eew-$VERSION-x86_64.AppImage"
else
    echo "   (omitido: falta linuxdeploy/appimagetool en el PATH)" >&2
fi

echo "-- 3/3: .deb y .rpm --"
# `fpm` produce los dos formatos pero exige Ruby; `dpkg-deb` viene en cualquier
# Debian/Ubuntu, incluido el runner de CI. El `.deb` es un archivo con un
# binario dentro: no hace falta una cadena de herramientas extra para armarlo, y
# depender de una significaba que en media de las máquinas el paso se omitía en
# silencio. El `.rpm` sí sigue necesitando fpm.
escribir_hooks_deb() {
    # A desktop entry is not visible the moment it is copied: the launcher
    # reads a database and the icon theme reads a cache, and both are built by
    # these two tools. Guarded and never fatal -- a machine without them still
    # gets a working package, one menu refresh later.
    local raiz="$1"
    local hook
    for hook in postinst postrm; do
        cat > "$raiz/DEBIAN/$hook" <<'HOOK'
#!/bin/sh
set -e
if command -v update-desktop-database >/dev/null 2>&1; then
    update-desktop-database -q /usr/share/applications || true
fi
if command -v gtk-update-icon-cache >/dev/null 2>&1; then
    gtk-update-icon-cache -q -f -t /usr/share/icons/hicolor || true
fi
exit 0
HOOK
        chmod 0755 "$raiz/DEBIAN/$hook"
    done
}

construir_deb_con_dpkg() {
    local raiz="$RAIZ/build/deb"
    rm -rf "$raiz"
    mkdir -p "$raiz/DEBIAN" "$raiz/usr/bin" "$raiz/usr/share/doc/vigia-eew"
    install -m 0755 "$BIN" "$raiz/usr/bin/vigia-eew"
    install -m 0644 "$RAIZ/README.md" "$raiz/usr/share/doc/vigia-eew/README.md"
    install -m 0644 "$RAIZ/LICENSE" "$raiz/usr/share/doc/vigia-eew/copyright"
    install -Dm 0644 "$RAIZ/packaging/vigia-eew.desktop" \
        "$raiz/usr/share/applications/vigia-eew.desktop"
    # A launcher entry of its own, not only the right-click action: GNOME hides
    # desktop actions behind a context menu nobody reported finding, and the
    # configuration is what people are looking for after installing.
    install -Dm 0644 "$RAIZ/packaging/vigia-eew-settings.desktop" \
        "$raiz/usr/share/applications/vigia-eew-settings.desktop"
    instalar_iconos_hicolor "$raiz"
    escribir_hooks_deb "$raiz"

    # El piso de glibc se deriva de la máquina que construye, no se inventa: un
    # binario de PyInstaller lleva dentro el runtime de Python enlazado contra
    # *esa* glibc, así que declarar una menor produciría un paquete que instala
    # y no arranca. En CI esa máquina es la base fijada por T-134.
    local glibc
    glibc="$(ldd --version | head -1 | grep -o '[0-9]\+\.[0-9]\+$')"
    local arch
    arch="$(dpkg --print-architecture)"
    local tamano
    tamano="$(du -ks "$raiz/usr" | cut -f1)"

    cat > "$raiz/DEBIAN/control" <<CONTROL
Package: vigia-eew
Version: $VERSION
Section: utils
Priority: optional
Architecture: $arch
Depends: libc6 (>= $glibc), zlib1g
Installed-Size: $tamano
Maintainer: Ernesto Crespo <ecrespo@gmail.com>
Homepage: https://github.com/ecrespo/vigia-eew
Description: Agente de escritorio de alerta sismica en tiempo real
 Vigia-eew vigila cuatro redes sismicas (EMSC, USGS, FUNVISIS y GEOFON) y
 muestra una alerta de escritorio cuando un sismo entra en el radio y la
 magnitud configurados. Guarda un historico local de lo que evaluo, con el
 motivo de cada descarte.
CONTROL
    dpkg-deb --build --root-owner-group "$raiz" "$DIST/vigia-eew_${VERSION}_${arch}.deb"
}

# fpm takes `source=destination` pairs; the same files the dpkg path installs.
MAPEOS_FPM=("$RAIZ/packaging/vigia-eew.desktop=/usr/share/applications/vigia-eew.desktop"
    "$RAIZ/packaging/vigia-eew-settings.desktop=/usr/share/applications/vigia-eew-settings.desktop"
    "$RAIZ/packaging/icons/vigia-eew.svg=/usr/share/icons/hicolor/scalable/apps/vigia-eew.svg")
for lado in "${TAMANOS_ICONO[@]}"; do
    MAPEOS_FPM+=("$RAIZ/packaging/icons/vigia-eew-$lado.png=/usr/share/icons/hicolor/${lado}x${lado}/apps/vigia-eew.png")
done

if command -v dpkg-deb >/dev/null; then
    construir_deb_con_dpkg
elif command -v fpm >/dev/null; then
    fpm -s dir -t deb -n vigia-eew -v "$VERSION" \
        --description "Agente de escritorio de alerta sísmica en tiempo real" \
        --url "https://github.com/ecrespo/vigia-eew" \
        --license "GPL-3.0-or-later" \
        --package "$DIST/vigia-eew_${VERSION}_amd64.deb" \
        "$BIN=/usr/bin/vigia-eew" "${MAPEOS_FPM[@]}"
else
    echo "   (omitido .deb: no hay dpkg-deb ni fpm en el PATH)" >&2
fi

if command -v fpm >/dev/null; then
    if command -v rpmbuild >/dev/null; then
        fpm -s dir -t rpm -n vigia-eew -v "$VERSION" \
            --description "Agente de escritorio de alerta sísmica en tiempo real" \
            --url "https://github.com/ecrespo/vigia-eew" \
            --package "$DIST/vigia-eew-${VERSION}.x86_64.rpm" \
            "$BIN=/usr/bin/vigia-eew" "${MAPEOS_FPM[@]}"
    else
        echo "   (omitido .rpm: falta rpmbuild en el PATH)" >&2
    fi
else
    echo "   (omitido .rpm: falta fpm en el PATH — gem install --no-document fpm)" >&2
fi

echo "== Listo. Artefactos en $DIST =="
ls -la "$DIST"
