#!/usr/bin/env python3
"""Validate the resources the packager bundles, before it runs (REQ-OPS-007).

Two consecutive releases shipped broken because of a packaging resource:
`7b1c71c`, an invalid placeholder icon, and `c38d9f6`, a *valid* PNG whose
resolution linuxdeploy rejects. The second is the instructive one -- "is it
a PNG" was never the question. The question is whether it is a PNG the
packager will accept, and the only way to answer it before the packager
runs is to ask here.

Stdlib only, deliberately: this has to run before anything is installed, and
`packaging/build_linux.sh` generates the AppImage icon the same way for the
same reason. Pillow is a runtime dependency of the product, not of its build.

Usage: `check_packaging_assets.py [repo-root]`
"""

from __future__ import annotations

import json
import struct
import sys
import wave
from dataclasses import dataclass
from pathlib import Path

_PNG_MAGIC = b"\x89PNG\r\n\x1a\n"

#: linuxdeploy accepts icons from 8x8 to 512x512. A 1x1 PNG parses fine and
#: is rejected anyway -- that is exactly what broke v0.1.2.
_MIN_ICON_SIDE = 8
_MAX_ICON_SIDE = 512

#: The name the desktop entry looks up in the icon theme, and therefore the
#: basename every installed icon file has to carry. `Icon=` is a lookup, not a
#: path: a name with nothing behind it renders as a grey placeholder and
#: nothing anywhere reports it.
ICON_NAME = "vigia-eew"

#: Keys without which a desktop entry installs cleanly and does nothing useful.
_DESKTOP_REQUIRED_KEYS = ("Type", "Name", "Exec", "Icon")


#: Hicolor sizes the Linux packages install. 22 and 24 are the panel sizes
#: GNOME and Xfce ask for; a theme that lacks them scales the nearest one.
ICON_PNG_SIDES: tuple[int, ...] = (16, 22, 24, 32, 48, 64, 128, 256, 512)


@dataclass(frozen=True)
class Asset:
    """A resource `packaging/vigia-eew.spec` bundles, and how to recognise a good one."""

    path: str
    kind: str


#: Everything under `src/vigia_eew/assets`, which the spec bundles wholesale
#: as `vigia_eew/assets` (packaging/vigia-eew.spec:41).
REQUIRED: tuple[Asset, ...] = (
    Asset("src/vigia_eew/assets/tray_icon.png", "icon"),
    Asset("src/vigia_eew/assets/critical.wav", "sound"),
    Asset("src/vigia_eew/assets/warning.wav", "sound"),
    Asset("src/vigia_eew/assets/info.wav", "sound"),
    Asset("src/vigia_eew/assets/countries.geojson", "geojson"),
)

#: The launcher resources, generated by `packaging/make_icons.py` and installed
#: by the three build scripts. They fail the way packaging resources always
#: fail -- quietly: a missing hicolor size gives a blurry panel icon, an `.ico`
#: the shell rejects gives the generic executable, and a desktop entry naming
#: an icon nobody installed gives a grey square. None of it raises anywhere.
LAUNCHER: tuple[Asset, ...] = (
    Asset("packaging/vigia-eew.desktop", "desktop"),
    Asset("packaging/vigia-eew-settings.desktop", "desktop"),
    Asset("packaging/icons/vigia-eew.svg", "svg"),
    Asset("packaging/icon.ico", "ico"),
    Asset("packaging/icon.icns", "icns"),
    *(Asset(f"packaging/icons/vigia-eew-{side}.png", "icon") for side in ICON_PNG_SIDES),
)


def _icon_problem(path: Path) -> str | None:
    data = path.read_bytes()
    if not data.startswith(_PNG_MAGIC):
        return f"{path.name}: not a PNG (bad signature)"
    if len(data) < 24:
        return f"{path.name}: truncated before its header"
    width, height = struct.unpack(">II", data[16:24])
    if not (_MIN_ICON_SIDE <= width <= _MAX_ICON_SIDE):
        return f"{path.name}: {width}x{height}, outside {_MIN_ICON_SIDE}..{_MAX_ICON_SIDE}"
    if not (_MIN_ICON_SIDE <= height <= _MAX_ICON_SIDE):
        return f"{path.name}: {width}x{height}, outside {_MIN_ICON_SIDE}..{_MAX_ICON_SIDE}"
    return None


def _sound_problem(path: Path) -> str | None:
    try:
        with wave.open(str(path), "rb") as handle:
            if handle.getnframes() <= 0:
                return f"{path.name}: no audio frames"
    except (wave.Error, EOFError) as exc:
        return f"{path.name}: not readable as WAV ({exc})"
    return None


def _geojson_problem(path: Path) -> str | None:
    try:
        parsed = json.loads(path.read_text())
    except (json.JSONDecodeError, UnicodeDecodeError) as exc:
        return f"{path.name}: not valid JSON ({exc})"
    if "features" not in parsed:
        return f"{path.name}: no 'features' key; not a FeatureCollection"
    return None


def desktop_problem(path: Path) -> str | None:
    """Everything wrong with a `.desktop` entry, short of installing it.

    Parsed rather than pattern-matched: the checks that matter are relations
    between keys -- an action declared in `Actions=` with no group behind it,
    an `Icon=` naming something no packager installs -- and a regex over the
    file cannot see either.
    """
    groups: dict[str, dict[str, str]] = {}
    current = ""
    for line in path.read_text(encoding="utf-8").splitlines():
        stripped = line.strip()
        if not stripped or stripped.startswith("#"):
            continue
        if stripped.startswith("[") and stripped.endswith("]"):
            current = stripped[1:-1]
            groups[current] = {}
        elif "=" in stripped and current:
            key, _, value = stripped.partition("=")
            groups[current][key.strip()] = value.strip()
    entry = groups.get("Desktop Entry")
    if entry is None:
        return f"{path.name}: no [Desktop Entry] group"
    missing = [key for key in _DESKTOP_REQUIRED_KEYS if key not in entry]
    if missing:
        return f"{path.name}: no {', '.join(missing)}"
    if entry["Icon"] != ICON_NAME:
        return f"{path.name}: Icon={entry['Icon']}, but the packages install '{ICON_NAME}'"
    for action in (name for name in entry.get("Actions", "").split(";") if name):
        group = groups.get(f"Desktop Action {action}")
        if group is None:
            return f"{path.name}: action {action} is declared with no group behind it"
        if "Exec" not in group or "Name" not in group:
            return f"{path.name}: action {action} has no Name/Exec"
    return None


def svg_problem(path: Path) -> str | None:
    text = path.read_text(encoding="utf-8", errors="replace")
    if "<svg" not in text:
        return f"{path.name}: no <svg> element"
    if "viewBox" not in text:
        return f"{path.name}: no viewBox; it will not scale"
    return None


def ico_problem(path: Path) -> str | None:
    """Whether the `.ico` is one the Windows shell will read (PNG entries, Vista+)."""
    data = path.read_bytes()
    if len(data) < 6:
        return f"{path.name}: truncated before its header"
    reserved, kind, count = struct.unpack("<HHH", data[:6])
    if (reserved, kind) != (0, 1) or count == 0:
        return f"{path.name}: not an icon directory"
    if len(data) < 6 + 16 * count:
        return f"{path.name}: declares {count} images its directory does not fit"
    for index in range(count):
        entry = 6 + index * 16
        length, offset = struct.unpack("<II", data[entry + 8 : entry + 16])
        if offset + length > len(data):
            return f"{path.name}: image {index + 1} runs past the end of the file"
    return None


def icns_problem(path: Path) -> str | None:
    """Whether the `.icns` parses as the Finder reads it: header, then elements."""
    data = path.read_bytes()
    if not data.startswith(b"icns"):
        return f"{path.name}: not an icns (bad magic)"
    declared = struct.unpack(">I", data[4:8])[0]
    if declared != len(data):
        return f"{path.name}: header says {declared} bytes, file is {len(data)}"
    offset = 8
    while offset < len(data):
        if offset + 8 > len(data):
            return f"{path.name}: element header truncated at byte {offset}"
        length = struct.unpack(">I", data[offset + 4 : offset + 8])[0]
        if length < 8 or offset + length > len(data):
            return f"{path.name}: element at byte {offset} declares {length} bytes"
        offset += length
    return None


_CHECKS = {
    "icon": _icon_problem,
    "sound": _sound_problem,
    "geojson": _geojson_problem,
    "desktop": desktop_problem,
    "svg": svg_problem,
    "ico": ico_problem,
    "icns": icns_problem,
}


def problems(root: Path, required: tuple[Asset, ...] = REQUIRED + LAUNCHER) -> list[str]:
    """Everything wrong with the packaging resources under `root`."""
    found: list[str] = []
    for asset in required:
        path = root / asset.path
        if not path.is_file():
            found.append(f"{asset.path}: missing")
            continue
        problem = _CHECKS[asset.kind](path)
        if problem is not None:
            found.append(problem)
    return found


def main(argv: list[str]) -> int:
    root = Path(argv[1]) if len(argv) > 1 else Path(__file__).resolve().parent.parent
    found = problems(root)
    if not found:
        print(f"Packaging assets: {len(REQUIRED) + len(LAUNCHER)} resources valid.")
        return 0
    print("Invalid packaging resources; not invoking the packager:", file=sys.stderr)
    for problem in found:
        print(f"  {problem}", file=sys.stderr)
    return 1


if __name__ == "__main__":
    raise SystemExit(main(sys.argv))
